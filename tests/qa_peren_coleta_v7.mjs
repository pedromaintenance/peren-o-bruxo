import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const ROOT=resolve(fileURLToPath(new URL('..',import.meta.url)));
const read=p=>readFileSync(resolve(ROOT,p));
const text=p=>read(p).toString('utf8');
const hash=b=>createHash('sha256').update(b).digest('hex');
const base='phaser-demo-m1hf/art/characters/peren/';
const m=JSON.parse(text(base+'official-v7/manifest.json'));
const bundle=text('phaser-demo-m1hf/assets/game-B5Gp97dd.js');
const sw=text('phaser-demo-m1hf/demo-sw.js');
const gallery=text('phaser-demo-m1hf/peren-arte.html');
const atlas=JSON.parse(text(base+'atlas.json'));
test('exact uploaded 20-pose RGBA collect atlas is in repository and loaded by Phaser',()=>{
 assert.equal(m.schema,'peren.collect.v7');assert.deepEqual(m.directions,['down','left','right','up']);
 const image=read(base+'peren-collect-atlas.png');
 assert.equal(hash(image),m.runtimeAsset.sha256);
 assert.equal(image.readUInt32BE(16),240);assert.equal(image.readUInt32BE(20),256);
 assert.match(bundle,/this\.load\.spritesheet\("peren-collect","\.\/art\/characters\/peren\/peren-collect-atlas\.png",\{frameWidth:48,frameHeight:64\}\)/);
 assert.match(bundle,/if\(K==="gather"\)continue/);
 assert.equal((bundle.match(/key:"peren-collect",frame:Y\*5\+\d,duration:\d+/g)||[]).length,5);
 assert.match(bundle,/const Z=`peren-\$\{X\}-gather`/);
 assert.match(bundle,/frameRate:1000\/244,repeat:0/);
});
test('all harvest targets use the same animation and finish through existing save pipeline',()=>{
 assert.match(bundle,/this\.playState\("gather"\)/);
 assert.doesNotMatch(bundle,/gather-herb|peren-herb/);
 assert.match(bundle,/this\.player\.once\(Rt\.Animations\.Events\.ANIMATION_COMPLETE/);
 assert.match(bundle,/Y\.execute\(\{type:"collect",seed:this\.world\.seed,nodeId:X\.id,world:this\.world\}\)/);
 assert.match(bundle,/peren-wounded/);
 assert.ok(atlas.runtime.gatherV7);
 assert.equal(atlas.runtime.gatherV7.texture,'peren-collect');
 assert.deepEqual(atlas.runtime.gatherV7.durationsMs,[300,160,220,180,360]);
 assert.equal(atlas.runtime.herbGather,undefined);
});
test('old herb-specific artifacts are gone; gallery and PWA use only generic collect',()=>{
 for(const path of [base+'peren-herb-atlas.png',base+'official-v5/peren-atlas-herb-v5.png',base+'official-v5/source-herb-gather-4x4.png'])assert.equal(existsSync(resolve(ROOT,path)),false,path);
 assert.doesNotMatch(gallery,/gather-herb|herbAtlas|ervas apenas/);
 assert.match(gallery,/value="gather">Coletando \(todos os itens, 5 quadros\)/);
 assert.match(gallery,/gatherDelays=\[300,160,220,180,360\]/);
 const files=JSON.parse(sw.match(/const FILES=(\[[^\n]+\]);/)[1]);
 assert.ok(files.includes('./art/characters/peren/peren-collect-atlas.png'));
 assert.ok(files.includes('./art/characters/peren/official-v7/manifest.json'));
 assert.equal(files.some(p=>/peren-herb-atlas|peren-atlas-herb-v5/.test(p)),false);
 assert.match(sw,/collect-v7-20261028/);
});