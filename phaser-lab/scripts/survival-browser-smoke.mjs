import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const url=process.env.PEREN_PREVIEW_URL||'http://127.0.0.1:4173/';
try{
 await page.goto(url,{waitUntil:'domcontentloaded',timeout:30000});
 await page.waitForFunction(()=>window.__perenProgress?.save?.worlds?.clock?.year===922,{timeout:30000});
 assert.match(await page.locator('#hubDay').textContent(),/922 EC/);
 assert.equal(await page.locator('#hubHungerValue').textContent(),'100 / 100');
 assert.equal(await page.locator('#hubRestValue').textContent(),'100 / 100');
 assert.match(await page.locator('#hubAvailableActions').textContent(),/Sem limite/);
 const before=await page.evaluate(()=>window.__perenProgress.save);
 assert.equal(before.character.actions,3);
 assert.equal(before.character.survival.physiology.form,'metamorfo');
 assert.equal(await page.locator('#regionSelect option').count(),10);
 await page.locator('#regionSelect').selectOption('caatinga');
 await page.locator('#travelRegion').click();
 await page.waitForFunction(()=>window.__perenLab.scene.getScene('ExplorationScene')?.world?.regionId==='caatinga');
 const travel=await page.evaluate(()=>window.__perenProgress.save);
 assert.ok(travel.character.survival.hunger<100);
 assert.ok(travel.character.survival.rest<100);
 assert.equal(travel.character.actions,3);
 assert.equal(travel.worlds.clock.year,922);
 await page.locator('#fieldEatBtn').click();
 await page.waitForFunction(old=>window.__perenProgress.save.character.bag['ger-racoes-de-viagem']===old-1,
  before.character.bag['ger-racoes-de-viagem'],{timeout:10000});
 const meal=await page.evaluate(()=>window.__perenProgress.save);
 assert.ok(meal.character.survival.hunger>travel.character.survival.hunger);
 assert.equal(meal.character.actions,3);
 await page.keyboard.press('Escape');
 await page.waitForSelector('#hub:not([hidden])');
 await page.locator('#sleepHours').selectOption('8');
 const restBefore=await page.evaluate(()=>window.__perenProgress.save);
 await page.locator('#endDayBtn').click();
 await page.waitForFunction(old=>window.__perenProgress.save.revision>old,restBefore.revision,{timeout:12000});
 const rested=await page.evaluate(()=>window.__perenProgress.save);
 assert.ok(rested.character.survival.rest>restBefore.character.survival.rest);
 assert.ok(rested.character.survival.hunger<restBefore.character.survival.hunger);
 assert.equal(rested.character.actions,3);
 assert.equal(rested.worlds.clock.minute,(restBefore.worlds.clock.minute+480)%1440);
 assert.equal(rested.worlds.clock.year,922);
 assert.match(await page.locator('#hubDay').textContent(),/922 EC/);
 assert.equal(await page.locator('#worldChronicleList li').count(),0,'future events should remain hidden');
 assert.match(await page.locator('#worldChronicleIntro').textContent(),/Rayquaza/);
 assert.deepEqual(errors,[],'Browser JS errors');
 console.log('Survival browser smoke: 922 EC, time travel, hunger, eat, 8h sleep, preservation of actions PASS');
}finally{await browser.close()}
